// Test-only helpers for code that used to call platform functions through the runtime pool.
//
// Since migration 017 the runtime role (qenbel_app) cannot execute platform_create_tenant, platform_set_tenant_status,
// expire_booking_holds, auth_lookup_* and the rest. Tests of other packages that need a tenant use createTestTenant(), which logs
// in as qenbel_platform_ops (or qenbel_auth for withTestAuthClient) on the SAME host and database as the given app pool or URL,
// with the password from QENBEL_PLATFORM_OPS_PASSWORD / QENBEL_AUTH_PASSWORD or, for local development, POSTGRES_PASSWORD from infra/.env.
//
// Refuses to run unless the database name ends in "_test". Each call opens and closes one connection (no pool is left open,
// so a test file never hangs on idle clients). Never use these in application code: the API and workers get their own
// DATABASE_PLATFORM_URL / DATABASE_AUTH_URL pools.
import { randomUUID } from "node:crypto";
import pg from "pg";
import { deriveRoleUrl, type LeastPrivilegeRole } from "./config.ts";
import type { Pool } from "./pool.ts";

export type PoolOrUrl = Pool | string;

export interface TestTenantOptions {
  /** Full slug. Default: `${slugPrefix ?? "test"}-<8 random hex>`. */
  slug?: string;
  slugPrefix?: string;
  /** Default: `Test <slug>`. */
  name?: string;
  /** Default 'salon' / '1.0.0'. Pass null for both to create a tenant without a pack. */
  packId?: string | null;
  packVersion?: string | null;
  /** Default 'Asia/Kolkata'. */
  timezone?: string;
  /** Default: generated by the database. */
  id?: string;
  /** Default 'central'. */
  deploymentMode?: "central" | "isolated";
}

function connectionStringOf(target: PoolOrUrl): string {
  if (typeof target === "string") return target;
  const cs = (target as unknown as { options?: { connectionString?: string } }).options?.connectionString;
  if (!cs) throw new Error("createTestTenant: the pool was not created from a connection string; pass the URL instead");
  return cs;
}

function roleUrl(target: PoolOrUrl, role: LeastPrivilegeRole): string {
  const base = connectionStringOf(target);
  let database: string;
  try {
    database = decodeURIComponent(new URL(base).pathname.replace(/^\//, ""));
  } catch {
    throw new Error("test helper: unparsable connection string");
  }
  if (!/_test$/.test(database)) {
    throw new Error(`test helper: refusing to run against "${database}": the database name must end in _test`);
  }
  if (process.env.NODE_ENV === "production") throw new Error("test helper: refusing to run with NODE_ENV=production");
  const url = deriveRoleUrl(base, role);
  if (!url) throw new Error(`test helper: no password for ${role} (set ${role === "qenbel_auth" ? "QENBEL_AUTH_PASSWORD" : "QENBEL_PLATFORM_OPS_PASSWORD"} or POSTGRES_PASSWORD in infra/.env)`);
  return url;
}

async function withRoleClient<T>(target: PoolOrUrl, role: LeastPrivilegeRole, fn: (client: pg.Client) => Promise<T>): Promise<T> {
  const client = new pg.Client({ connectionString: roleUrl(target, role), application_name: `qenbel-test-${role}` });
  await client.connect();
  try {
    return await fn(client);
  } finally {
    await client.end();
  }
}

/** One connection as qenbel_platform_ops (tenant lifecycle, sweeps, purge) on the test database of `target`. */
export function withTestPlatformClient<T>(target: PoolOrUrl, fn: (client: pg.Client) => Promise<T>): Promise<T> {
  return withRoleClient(target, "qenbel_platform_ops", fn);
}

/** One connection as qenbel_auth (auth_lookup_user / auth_lookup_credential / auth_is_platform_admin) on the test database of `target`. */
export function withTestAuthClient<T>(target: PoolOrUrl, fn: (client: pg.Client) => Promise<T>): Promise<T> {
  return withRoleClient(target, "qenbel_auth", fn);
}

/** Create a tenant through platform_create_tenant as qenbel_platform_ops. Returns its id. Test databases only. */
export async function createTestTenant(target: PoolOrUrl, options: TestTenantOptions = {}): Promise<string> {
  const slug = options.slug ?? `${options.slugPrefix ?? "test"}-${randomUUID().slice(0, 8)}`;
  const packId = options.packId === undefined ? "salon" : options.packId;
  const packVersion = options.packVersion === undefined ? (packId === null ? null : "1.0.0") : options.packVersion;
  return withTestPlatformClient(target, async (c) => {
    const res = await c.query<{ id: string }>(
      "select platform_create_tenant($1, $2, $3, $4, $5, $6, $7) as id",
      [slug, options.name ?? `Test ${slug}`, options.deploymentMode ?? "central", packId, packVersion, options.timezone ?? "Asia/Kolkata", options.id ?? null],
    );
    return (res.rows[0] as { id: string }).id;
  });
}

/** platform_set_tenant_status as qenbel_platform_ops. Test databases only. */
export async function setTestTenantStatus(target: PoolOrUrl, tenantId: string, status: "active" | "suspended" | "archived"): Promise<void> {
  await withTestPlatformClient(target, (c) => c.query("select platform_set_tenant_status($1, $2)", [tenantId, status]));
}
